# ── Report sections ────────────────────────────────────────────────────────────

def get_cluster_summary(base_url: str) -> dict:
    node_count = query_prometheus(base_url, "count(kube_node_info)")
    pod_count  = query_prometheus(base_url, "count(kube_pod_info)")
    cpu_avg    = query_prometheus(base_url,
        'avg(rate(node_cpu_seconds_total{mode!="idle"}[1h])) * 100')
    mem_avg    = query_prometheus(base_url,
        '(1 - avg(node_memory_MemAvailable_bytes / node_memory_MemTotal_bytes)) * 100')

    def first_value(result):
        if result and result[0].get("value"):
            return round(float(result[0]["value"][1]), 2)
        return "N/A"

    return {
        "nodes":   first_value(node_count),
        "pods":    first_value(pod_count),
        "cpu_pct": first_value(cpu_avg),
        "mem_pct": first_value(mem_avg),
    }


def get_alert_summary(base_url: str) -> list:
    firing = query_prometheus(base_url, 'ALERTS{alertstate="firing"}')
    alerts = []
    for item in firing:
        alerts.append({
            "name":      item["metric"].get("alertname", "unknown"),
            "severity":  item["metric"].get("severity", "unknown"),
            "namespace": item["metric"].get("namespace", "cluster"),
        })
    return alerts


# ── HTML report ───────────────────────────────────────────────────────────────

def build_html_report(summary: dict, alerts: list, week_start: str) -> str:
    alert_rows = "".join(
        f"<tr><td>{a['name']}</td><td>{a['severity']}</td><td>{a['namespace']}</td></tr>"
        for a in alerts
    ) or "<tr><td colspan='3' style='color:green'>No active alerts</td></tr>"

    return f"""<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <style>
    body  {{ font-family: Arial, sans-serif; font-size: 14px; color: #333; }}
    h1    {{ color: #1a3a5c; }}
    table {{ border-collapse: collapse; width: 100%; margin-top: 12px; }}
    th    {{ background: #1a3a5c; color: white; padding: 8px; text-align: left; }}
    td    {{ border: 1px solid #ddd; padding: 8px; }}
    .stat {{ display: inline-block; background: #f5f5f5; border-radius: 6px;
             padding: 12px 20px; margin: 8px; text-align: center; min-width: 120px; }}
    .stat-val {{ font-size: 24px; font-weight: bold; color: #1a3a5c; }}
  </style>
</head>
<body>
  <h1>Weekly Kubernetes Cluster Report</h1>
  <p>Week of <strong>{week_start}</strong> · Generated {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}</p>

  <h2>Cluster Overview</h2>
  <div>
    <div class="stat"><div class="stat-val">{summary['nodes']}</div>Nodes</div>
    <div class="stat"><div class="stat-val">{summary['pods']}</div>Running Pods</div>
    <div class="stat"><div class="stat-val">{summary['cpu_pct']}%</div>Avg CPU</div>
    <div class="stat"><div class="stat-val">{summary['mem_pct']}%</div>Avg Memory</div>
  </div>

  <h2>Active Alerts</h2>
  <table>
    <tr><th>Alert Name</th><th>Severity</th><th>Namespace</th></tr>
    {alert_rows}
  </table>

  <p style="color:#888;font-size:12px;margin-top:20px">
    Generated by metrics-report.py · k8s-observability project
  </p>
</body>
</html>"""


# ── Main ───────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(description="Generate weekly Prometheus metrics report")
    parser.add_argument("--prometheus-url", default="http://localhost:9090")
    parser.add_argument("--output", default="weekly-report.html",
                        help="Write HTML report to this file")
    parser.add_argument("--email-to",   help="Send report to this address")
    parser.add_argument("--email-from", default="alerts@k8s-cluster.local")
    parser.add_argument("--smtp-host",  default="localhost")
    args = parser.parse_args()

    week_start = (datetime.now(timezone.utc) - timedelta(days=7)).strftime("%Y-%m-%d")

    print(f"Querying Prometheus at {args.prometheus_url} ...")
    summary = get_cluster_summary(args.prometheus_url)
    alerts  = get_alert_summary(args.prometheus_url)

    html = build_html_report(summary, alerts, week_start)

    with open(args.output, "w") as f:
        f.write(html)
    print(f"Report saved: {args.output}")

    if args.email_to:
        msg = MIMEMultipart("alternative")
        msg["Subject"] = f"Weekly K8s Cluster Report — {week_start}"
        msg["From"]    = args.email_from
        msg["To"]      = args.email_to
        msg.attach(MIMEText(html, "html"))
        with smtplib.SMTP(args.smtp_host) as server:
            server.sendmail(args.email_from, args.email_to, msg.as_string())
        print(f"Report emailed to {args.email_to}")


if __name__ == "__main__":
    main()
