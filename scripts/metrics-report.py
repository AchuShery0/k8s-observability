#!/usr/bin/env python3
"""
metrics-report.py — Query Prometheus and generate a weekly summary report
Usage: python3 scripts/metrics-report.py --prometheus-url http://localhost:9090
"""

import argparse
import json
import smtplib
import sys
import urllib.request
from datetime import datetime, timedelta, timezone
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText


# ── Prometheus query helper ────────────────────────────────────────────────────

def query_prometheus(base_url: str, promql: str) -> list:
    encoded = urllib.parse.quote(promql)
    url = f"{base_url}/api/v1/query?query={encoded}"
    try:
        with urllib.request.urlopen(url, timeout=10) as resp:
            data = json.loads(resp.read())
            if data.get("status") == "success":
                return data["data"]["result"]
    except Exception as exc:
        print(f"WARN: Prometheus query failed: {exc}", file=sys.stderr)
    return []


